// 테이블 객체 편집기 DDL 조립·식별자 인용(src/lib/sql-obj-ddl.ts) — 실행 : pnpm test
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { buildDdl, lit, qi, qid, type DdlIn } from '../src/lib/sql-obj-ddl.ts'

const base = (o: Partial<DdlIn> = {}): DdlIn => ({
  schema: 'public', name: 't', kind: 'r', persistence: 'p', owner: null, tablespace: null, am: null, rls: false, partKey: null, partOf: null, inherits: [],
  options: null, comment: null, viewDef: null, foreign: null, seq: null, cols: [], cons: [], fks: [], idx: [], trg: [], rules: [], pol: [], grants: [], ...o,
})
const col = (name: string, x: Partial<DdlIn['cols'][number]> = {}) => ({ name, type: 'integer', collation: null, nn: false, default: null, identity: null, generated: false, local: true, comment: null, ...x })

test('식별자 인용 — qid 는 항상, qi 는 대문자·특수문자·예약어만', () => {
  assert.equal(qid('a"b'), '"a""b"')
  assert.equal(qid('x"; DROP TABLE y; --'), '"x""; DROP TABLE y; --"')
  assert.equal(qi('std_dic'), 'std_dic')
  assert.equal(qi('User'), '"User"')
  assert.equal(qi('user'), '"user"')
  assert.equal(qi('order'), '"order"')
  assert.equal(qi('한글'), '"한글"')
  assert.equal(lit("it's"), "'it''s'")
})

test('테이블 DDL — 칼럼·제약 인라인 → 인덱스 → 코멘트 → 트리거 → RLS → 정책 → 권한 → FK 순서', () => {
  const d = buildDdl(
    base({
      owner: 'postgres', rls: true, comment: "코드 '상세'", options: ['fillfactor=90'], tablespace: 'ts1',
      cols: [col('id', { type: 'bigint', nn: true, identity: 'd' }), col('nm', { type: 'character varying(100)', collation: 'C', default: "'x'::character varying", comment: '이름' }), col('amt', { type: 'numeric', generated: true, default: '(id * 2)' })],
      cons: [{ name: 't_pkey', definition: 'PRIMARY KEY (id)', comment: null }],
      fks: [{ name: 't_fk', definition: 'FOREIGN KEY (id) REFERENCES public.r(id)', comment: 'FK 설명' }],
      idx: [{ name: 't_nm_idx', schema: 'public', definition: 'CREATE INDEX t_nm_idx ON public.t USING btree (nm)', comment: null }],
      trg: [{ name: 'tg', definition: 'CREATE TRIGGER tg BEFORE UPDATE ON public.t FOR EACH ROW EXECUTE FUNCTION f()', comment: null }],
      pol: [{ name: 'p1', permissive: 'PERMISSIVE', command: 'SELECT', roles: 'PUBLIC', using: 'true', with_check: null }],
      grants: [{ grantee: 'postgres', privilege: 'SELECT', grantable: false, column: null }, { grantee: 'postgres', privilege: 'INSERT', grantable: false, column: null }, { grantee: 'ro', privilege: 'SELECT', grantable: false, column: 'nm' }],
    }),
  )
  assert.match(d, /^-- DROP TABLE public\.t;/)
  assert.match(d, /CREATE TABLE public\.t \(\n\tid bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n\tnm character varying\(100\) COLLATE "C" NULL DEFAULT 'x'::character varying,\n\tamt numeric GENERATED ALWAYS AS \(\(id \* 2\)\) STORED NULL,\n\tCONSTRAINT t_pkey PRIMARY KEY \(id\)\n\)\nWITH \(\n\tfillfactor=90\n\)\nTABLESPACE ts1;/)
  assert.match(d, /COMMENT ON TABLE public\.t IS '코드 ''상세''';/)
  assert.match(d, /COMMENT ON COLUMN public\.t\.nm IS '이름';/)
  assert.match(d, /COMMENT ON CONSTRAINT t_fk ON public\.t IS 'FK 설명';/)
  assert.match(d, /GRANT SELECT, INSERT ON TABLE public\.t TO postgres;/)
  assert.match(d, /GRANT SELECT\(nm\) ON TABLE public\.t TO ro;/)
  assert.match(d, /ALTER TABLE public\.t ADD CONSTRAINT t_fk FOREIGN KEY \(id\) REFERENCES public\.r\(id\);\n$/)
  const at = (s: string) => d.indexOf(s)
  const order = ['CREATE TABLE', 'CREATE INDEX', 'COMMENT ON TABLE', 'COMMENT ON COLUMN', 'CREATE TRIGGER', 'ENABLE ROW LEVEL SECURITY', 'CREATE POLICY', 'OWNER TO', 'GRANT', 'ADD CONSTRAINT t_fk']
  for (let i = 1; i < order.length; i++) assert.ok(at(order[i - 1]) < at(order[i]), `${order[i - 1]} → ${order[i]}`)
  assert.ok(!d.includes('DEFAULT (id * 2)'), '생성 칼럼은 DEFAULT 로 쓰지 않음')
})

test('상속 칼럼 제외 + INHERITS, 파티션 키, 파티션 자식, 뷰, 시퀀스', () => {
  const inh = buildDdl(base({ name: 'Child', cols: [col('id', { local: false }), col('x')], inherits: [{ schema: 'public', name: 'p' }] }))
  assert.match(inh, /CREATE TABLE public\."Child" \(\n\tx integer NULL\n\)\nINHERITS \(public\.p\);/)
  assert.match(buildDdl(base({ kind: 'p', cols: [col('d')], partKey: 'RANGE (d)' })), /\)\nPARTITION BY RANGE \(d\);/)
  assert.match(buildDdl(base({ partOf: { schema: 'public', name: 'p', bound: "FOR VALUES FROM ('2026-01-01') TO ('2027-01-01')" } })), /CREATE TABLE public\.t PARTITION OF public\.p FOR VALUES FROM/)
  const v = buildDdl(base({ kind: 'v', viewDef: ' SELECT 1 AS a;', owner: 'o' }))
  assert.match(v, /CREATE OR REPLACE VIEW public\.t\nAS SELECT 1 AS a;/)
  assert.match(v, /ALTER VIEW public\.t OWNER TO o;/)
  assert.match(buildDdl(base({ kind: 'm', viewDef: 'SELECT 1;' })), /CREATE MATERIALIZED VIEW public\.t\nAS SELECT 1\nWITH DATA;/)
  assert.match(buildDdl(base({ kind: 'S', seq: { type: 'bigint', start: '1', inc: '1', min: '1', max: '9223372036854775807', cache: '1', cycle: false } })), /CREATE SEQUENCE public\.t\n\tAS bigint\n\tINCREMENT BY 1[\s\S]*NO CYCLE;/)
  assert.match(buildDdl(base({ persistence: 'u', cols: [col('a')] })), /^-- DROP TABLE public\.t;\n\nCREATE UNLOGGED TABLE/)
})

test('보안 회귀 : 카탈로그 이름의 개행이 주석 줄을 끊고 SQL 문장이 되지 않음(2026-10-20)', () => {
  const d = buildDdl(base({ name: 'x\nDROP TABLE victim; --', cols: [col('id')] }))
  assert.ok(!d.startsWith('-- DROP TABLE public."x\n')) // 주석 줄이 개행으로 끊기지 않음(CREATE 의 따옴표 식별자 안 개행은 식별자 일부라 무해)
  assert.match(d, /^-- DROP TABLE public\."x DROP TABLE victim; --";$/m)
})

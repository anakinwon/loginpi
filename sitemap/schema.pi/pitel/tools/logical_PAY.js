// 앞쪽 단어부터 비교해 먼저 긴 단어가 나오는 쪽
const longerFirst = (x, y) => {
  for (let k = 0; k < Math.min(x.length, y.length); k++) if (x[k].length !== y[k].length) return x[k].length > y[k].length
  return false
}
// 최소 단어 수 → 1글자 단어 적은 쪽 → 앞 단어가 긴 쪽(03_standards 2-4)
function segment(nm) {
  const n = nm.length
  const best = Array(n + 1).fill(null)
  best[0] = { parts: [], cnt: 0, one: 0 }
  for (let i = 0; i < n; i++) {
    if (!best[i]) continue
    for (let j = n; j > i; j--) {
      const s = nm.slice(i, j)
      if (!wordMap.has(s)) continue
      const c = { parts: [...best[i].parts, s], cnt: best[i].cnt + 1, one: best[i].one + (s.length === 1 ? 1 : 0) }
      const b = best[j]
      if (!b || c.cnt < b.cnt || (c.cnt === b.cnt && (c.one < b.one || (c.one === b.one && longerFirst(c.parts, b.parts))))) best[j] = c
    }
  }
  return best[n] && best[n].parts
}

const newTerms = new Map()
function resolveTerm(attrNm, domOverride, def) {
  const t = termMap.get(attrNm)
  if (t) return { phyNm: t.phyNm, domNm: domOverride || t.domNm, def: t.def }
  const parts = segment(attrNm)
  if (!parts) throw new Error('단어 분할 실패 : ' + attrNm)
  const last = wordMap.get(parts[parts.length - 1])
  if (!last.attrClss) throw new Error('속성 분류어로 끝나지 않음 : ' + attrNm)
  const domNm = domOverride || DEF_DOM[last.keyDom]
  if (!domSet.has(domNm)) throw new Error('도메인 없음 : ' + attrNm + ' ' + domNm)
  const phyNm = parts.map((p) => wordMap.get(p).abbr).join('_')
  const nw = parts.filter((p) => NEW_WORDS.some((x) => x.wordNm === p))
  const nt = { termNm: attrNm, words: parts, phyNm, domNm, def: def || attrNm }
  if (nw.length) nt.newWords = NEW_WORDS.filter((x) => nw.includes(x.wordNm)).map(({ wordNm, abbr, engNm }) => ({ wordNm, abbr, engNm }))
  if (!newTerms.has(attrNm)) newTerms.set(attrNm, nt)
  return { phyNm, domNm, def: nt.def }
}

// 엔터티 물리명 = <단어 약어>_<분류어 약어>(02 관문 K1, 개념 모델과 동일), 테이블명 미리보기 tblNm = PTL_PAY_<분류어 앞 단어 약어>_<접미어>
function entPhy(entNm) {
  const parts = segment(entNm)
  if (!parts) throw new Error('엔터티명 분할 실패 : ' + entNm)
  return parts.map((p) => wordMap.get(p).abbr).join('_')
}
function entTbl(entNm) {
  const parts = segment(entNm)
  if (!parts) throw new Error('엔터티명 분할 실패 : ' + entNm)
  const cls = wordMap.get(parts[parts.length - 1])
  if (!cls.entClss) throw new Error('엔터티 분류어로 끝나지 않음 : ' + entNm)
  return 'PTL_PAY_' + parts.slice(0, -1).map((p) => wordMap.get(p).abbr).join('_') + cls.tblSfx
}


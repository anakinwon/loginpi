// 새 공통코드 후보(표준 담당이 tools/std_codes.js 원장에 반영) — 정의 문구의 값 목록에서 생성
function codeVals(def) {
  const m = def && def.match(/^(.*?) — 공통코드/)
  if (!m) return null
  const list = m[1].replace(/^최초 계산은 NULL, /, '').split('·')
  return list.map((nm, i) => ({ cd: String(i + 1).padStart(2, '0'), nm: nm.trim(), def: nm.trim() }))
}


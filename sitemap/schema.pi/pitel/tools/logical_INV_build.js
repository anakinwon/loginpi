  const seg = segment(e.nm)
  if (!seg) { errs.push('엔터티명 분할 불가 ' + e.nm); continue }
  const last = seg[seg.length - 1]
  if (!last.entClss) errs.push('엔터티 분류어 아님 ' + e.nm)
  const attrs = e.a.map(([nm, fl = '', fk = null, def = null, dom = null]) => {
    const t = term(nm, dom)
    let fkObj = null
    if (fk) {
      const [ent, pa] = fk.split('@')
      const local = !ent.includes('.')
      fkObj = { area: local ? 'INV' : ent.split('.')[0], ent: ent.replace(/^[A-Z]+\./, ''), attr: pa || nm }
      if (local && !entIdx.has(ent)) errs.push('FK 부모 없음 ' + ent)
      else if (local && !ENTS[entIdx.get(ent)].a.some((x) => x[0] === fkObj.attr && x[1].includes('P'))) errs.push(`FK 속성이 부모 PK 아님 ${e.nm}.${nm}→${ent}`)
    }
    const role = (fl.match(/R:(\w+)/) || [])[1]
    return { attrNm: nm, phyNm: t.phyNm, domNm: t.domNm, pk: fl.includes('P'), fk: fkObj, nullYn: !(fl.includes('P') || fl.includes('!')), def: def || t.def, ...(role ? { role } : {}) }
  })
  // 속성 순서 PK → FK → 일반(명세 순서 유지)
  const pOf = (a) => (a.fk.area === 'INV' ? a.fk.ent : a.fk.area + '.' + a.fk.ent)
  const rank = (a) => (a.pk ? 0 : a.fk ? 1 : 2)
  attrs.sort((x, y) => rank(x) - rank(y))
  attrs.forEach((a, k) => { a.seq = k + 1 })
  // 관계 = FK 부모별 1건(자식 쪽에 기록)
  const rels = []
  for (const p of [...new Set(attrs.filter((a) => a.fk).map(pOf))]) {
    const fkAttrs = COMPOSITE[`${e.nm}>${p}`] || attrs.filter((a) => a.fk && pOf(a) === p).map((a) => a.attrNm)
    const fa = fkAttrs.map((n) => attrs.find((a) => a.attrNm === n))
    const role = attrs.find((a) => a.fk && pOf(a) === p && a.fk.attr !== a.attrNm)
    const r = { relNm: `${p.replace(/^[A-Z]+\./, '')} → ${e.nm}${role ? '(' + role.attrNm + ')' : ''}`, parent: p, child: e.nm, card: ONE_TO_ONE.has(`${p}>${e.nm}`) ? '1:1' : '1:N', idn: fa.every((a) => a.pk), opt: fa.some((a) => a.nullYn), fkAttrs }
    rels.push(r)
    relAll.push(r)
  }
  if (e.stg === 'CNCP') for (const r of ['PK', 'NM', 'DTM', 'STS']) if (!attrs.some((a) => a.role === r)) errs.push(`핵심 필수 ${r} 없음 ${e.nm}`)
